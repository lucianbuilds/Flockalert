<#
.SYNOPSIS
  Turns the output of cameras.overpassql into flockalert/esp32/coordinates.h.

.DESCRIPTION
  Reads the tab-separated name/lat/lon rows that Overpass Turbo returns
  and writes a complete coordinates.h, replacing the existing file.
  Use git to compare or undo.

.EXAMPLE
  ./tools/overpass/make-coordinates.ps1 -InputFile export.csv

.EXAMPLE
  # Copy the Data tab in Overpass Turbo, then:
  ./tools/overpass/make-coordinates.ps1 -FromClipboard
#>
param(
  [string]$InputFile,
  [switch]$FromClipboard,
  [string]$OutFile = (Join-Path $PSScriptRoot '..\..\flockalert\esp32\coordinates.h'),
  [int]$Decimals = 5
)

if ($FromClipboard) {
  $text = (Get-Clipboard) -join "`n"
} elseif ($InputFile) {
  $text = Get-Content -Raw -Encoding UTF8 $InputFile
} else {
  throw 'Pass -InputFile <path> or -FromClipboard.'
}

$rows = ($text -split "\r?\n" | Where-Object { $_.Trim() }) | ConvertFrom-Csv -Delimiter "`t"
$inv = [Globalization.CultureInfo]::InvariantCulture
$fmt = 'F' + $Decimals
$seen = @{}
$lines = foreach ($r in $rows) {
  if (-not $r.lat -or -not $r.lon) { continue }
  $lat = [double]::Parse($r.lat, $inv).ToString($fmt, $inv)
  $lon = [double]::Parse($r.lon, $inv).ToString($fmt, $inv)
  $name = ($r.name -replace '\\', '\\' -replace '"', '\"')
  $key = "$name|$lat|$lon"
  if ($seen.ContainsKey($key)) { continue }
  $seen[$key] = $true
  "  { `"$name`", $lat, $lon },"
}

if (-not $lines) { throw 'No rows found. Is this the output of cameras.overpassql?' }

$header = @'
#ifndef COORDINATES_H
#define COORDINATES_H

// ============================================================
// COORDINATE DATABASE
// Generated by tools/overpass/make-coordinates.ps1
// Data (c) OpenStreetMap contributors, ODbL
// ============================================================

struct Waypoint {
  const char* name;
  double latitude;
  double longitude;
};

const Waypoint waypoints[] = {

'@

$footer = @'

};

const size_t WAYPOINT_COUNT =
  sizeof(waypoints) / sizeof(waypoints[0]);

#endif
'@

$content = $header + ($lines -join "`n") + "`n" + $footer + "`n"
$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
[IO.File]::WriteAllText([IO.Path]::GetFullPath($OutFile), $content, $utf8NoBom)

$alpr = @($lines | Where-Object { $_ -like '*ALPR"*' }).Count
Write-Host "Wrote $($lines.Count) entries ($alpr ALPR, $($lines.Count - $alpr) other) to $OutFile"
